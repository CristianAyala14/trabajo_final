const { test } = require("node:test");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");

const url = process.env.CLIENTES_TEST_DB_URL;
test("Clientes: ciclo HTTP, restricciones y conservación del historial en PostgreSQL", { skip: !url && "Definí CLIENTES_TEST_DB_URL para la integración" }, async t => {
  process.env.DB_URL = url;
  const { conn } = require("../db");
  const app = require("../app");
  const schema = "test_clientes_" + randomUUID().replaceAll("-", "");
  conn.addHook("afterConnect", connection => connection.query(`SET search_path TO "${schema}"`));
  t.after(() => conn.close());
  await conn.query(`CREATE SCHEMA "${schema}"`);
  try {
    await conn.query(`CREATE TABLE provincia (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre varchar(100) UNIQUE NOT NULL);
      CREATE TABLE cliente (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre varchar(200) NOT NULL,
        razon_social varchar(200), identificacion_fiscal varchar(30) UNIQUE, telefono varchar(40), domicilio text,
        email varchar(254), provincia_id bigint REFERENCES provincia ON DELETE RESTRICT, activo boolean NOT NULL DEFAULT true);
      CREATE TABLE contrato (id bigint PRIMARY KEY, cliente_id bigint NOT NULL REFERENCES cliente ON DELETE RESTRICT);
      INSERT INTO provincia (nombre) VALUES ('Mendoza');`);
    const http = await new Promise((resolve, reject) => {
      const server = app.listen(0, "127.0.0.1", () => resolve(server));
      server.once("error", reject);
    });
    try {
      const base = `http://127.0.0.1:${http.address().port}/clientes`;
      const call = async (method, path, body, code) => {
        const response = await fetch(base + path, { method, headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
        const data = await response.json();
        assert.equal(response.status, code, JSON.stringify(data));
        return data;
      };
      const uno = await call("POST", "", { nombre: "  Ada  " }, 201);
      assert.equal(uno.nombre, "Ada");
      assert.equal(uno.activo, true);
      const dos = await call("POST", "", { nombre: "Otro", identificacionFiscal: "   " }, 201);
      assert.equal(dos.identificacionFiscal, null);
      await call("PUT", "/" + uno.id, { identificacionFiscal: " REF-01 ", provinciaId: "1", email: "ada@example.com" }, 200);
      await call("POST", "", { nombre: "Duplicado", identificacionFiscal: "REF-01" }, 409);
      await call("PUT", "/" + dos.id, { identificacionFiscal: "REF-01" }, 409);
      await call("PUT", "/" + uno.id, { provinciaId: 99 }, 400);
      for (const body of [{ nombre: " " }, { nombre: "A", activo: false }, { nombre: "A", id: 9 }, { nombre: "A", email: "no-es-correo" }, { nombre: "A".repeat(201) }]) {
        await call("POST", "", body, 400);
      }
      await call("GET", "/9223372036854775808", undefined, 400);
      await call("GET", "/999", undefined, 404);
      await call("PUT", "/" + uno.id, {}, 400);
      const editado = await call("PUT", "/" + uno.id, { email: null }, 200);
      assert.equal(editado.email, null);
      assert.equal(editado.provinciaId, "1");
      await conn.query("INSERT INTO contrato(id, cliente_id) VALUES (1, $1)", { bind: [uno.id] });
      await call("DELETE", "/" + uno.id, undefined, 200);
      const historico = await call("GET", "/" + uno.id, undefined, 200);
      assert.equal(historico.activo, false);
      assert.deepEqual((await call("GET", "", undefined, 200)).map(c => c.id), [dos.id]);
      await call("PUT", "/" + uno.id, { nombre: "Cambio" }, 404);
      await call("DELETE", "/" + uno.id, undefined, 404);
      const [contratos] = await conn.query("SELECT cliente_id FROM contrato");
      assert.equal(contratos[0].cliente_id, uno.id);
    } finally { await new Promise(resolve => http.close(resolve)); }
  } finally {
    await conn.query(`DROP SCHEMA "${schema}" CASCADE`);
  }
});
